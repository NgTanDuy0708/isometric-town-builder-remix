"""Copy native image_gen atlases and record source rectangles, without editing PNGs."""
from pathlib import Path
from PIL import Image
import hashlib,json,shutil,statistics

root=Path(__file__).resolve().parents[1]
source=Path(r'C:/Users/ntduy/.codex/generated_images/01a17baa-0a4e-7470-8df2-a436b2f8749f')
names={'dragon':'exec-fcc1c0af-b67d-42be-a3aa-f13bcdd95199.png','troll':'exec-31d8f759-20d4-48da-8268-5ca0fe835141.png'}
records={}
for kind,filename in names.items():
    path=source/filename
    target=root/f'public/assets/combat/v2/{kind}.png'
    target.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(path,target)
    im=Image.open(path).convert('RGBA');w,h=im.size
    directions={}
    for row,direction in enumerate(['SE','SW','NE','NW']):
        frames=[]
        for col in range(4):
            x0,y0,x1,y1=col*w//4,row*h//4,(col+1)*w//4,(row+1)*h//4
            alpha=im.getchannel('A').crop((x0,y0,x1,y1))
            bounds=alpha.point(lambda v:255 if v>100 else 0).getbbox()
            if not bounds:raise RuntimeError(f'Empty cell: {kind} {row} {col}')
            l,t,r,b=bounds
            bottom=[(x,alpha.getpixel((x,y))) for y in range(max(t,b-12),b) for x in range(l,r) if alpha.getpixel((x,y))>100]
            anchor=sum(x*a for x,a in bottom)/sum(a for x,a in bottom)
            frames.append({'x':x0+l,'y':y0+t,'w':r-l,'h':b-t,'anchorX':round(anchor-l,3),'anchorY':b-t})
        directions[direction]=frames
    records[kind]={'uri':f'/assets/combat/v2/{kind}.png','width':w,'height':h,'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
      'referenceHeight':statistics.median(f['h'] for frames in directions.values() for f in frames),'directions':directions,'nativeSource':str(path)}
(root/'src/data/raidArtData.js').write_text('// Native image_gen atlases; generated by scripts/recordRaidAssets.py.\nexport const RAID_SHEETS = '+json.dumps(records,indent=2)+';\n',encoding='utf-8')
out=root/'docs/generated-assets/raids-v2';out.mkdir(parents=True,exist_ok=True)
(out/'manifest.json').write_text(json.dumps(records,indent=2),encoding='utf-8')
print({k:(r['width'],r['height'],len(r['directions'])*4) for k,r in records.items()})
