import fs from 'node:fs';
import crypto from 'node:crypto';
import {inspectPng} from './pngMetadata.mjs';

const dir='docs/generated-assets/single-seeds';
const {jobs}=JSON.parse(fs.readFileSync(dir+'/prompt-set.json','utf8'));
const outputs=JSON.parse(fs.readFileSync(dir+'/outputs.json','utf8'));
const data={},items=[];
for(const job of jobs){
  const generatedPath=outputs[job.id];
  if(!generatedPath)throw Error('Missing output: '+job.id);
  const bytes=fs.readFileSync(generatedPath),metadata=inspectPng(bytes);
  const [left,top,right,bottom]=metadata.opaqueBounds;
  if(metadata.alphaMin!==0||metadata.alphaMax!==255||left<=0||top<=0||right>=metadata.width||bottom>=metadata.height)
    throw Error('Expected complete isolated seed with true alpha: '+job.id);
  const sha256=crypto.createHash('sha256').update(bytes).digest('hex');
  const filename=job.id+(job.kind==='fruit'?'_seed.png':'_sown.png');
  const sourcePath='assets-source/seeds/single-v1/'+filename;
  const gameAssetPath='public/assets/seeds/single-v1/'+filename;
  for(const file of [sourcePath,gameAssetPath]){
    fs.mkdirSync(file.slice(0,file.lastIndexOf('/')),{recursive:true});
    if(fs.existsSync(file)){
      if(!fs.readFileSync(file).equals(bytes))throw Error('Refusing to overwrite different PNG: '+file);
    }else fs.writeFileSync(file,bytes);
  }
  const generationPromptPath=dir+'/'+job.id+'.actual.txt';
  fs.writeFileSync(generationPromptPath,job.prompt+'\n');
  const anchor={x:(left+right)/2,y:bottom-1};
  data[job.id]={uri:'/assets/seeds/single-v1/'+filename+'?v='+sha256.slice(0,12),sha256,
    width:metadata.width,height:metadata.height,bounds:metadata.opaqueBounds,anchor};
  items.push({...job,filename,generatedPath,sourcePath,gameAssetPath,generationPromptPath,sha256,metadata,anchor,status:'generated',uri:data[job.id].uri});
}
fs.writeFileSync(dir+'/manifest.json',JSON.stringify({mode:'built-in',items},null,2)+'\n');
fs.writeFileSync('src/data/singleSeedSpriteData.js','// Native PNG geometry; generated by scripts/recordSingleSeedAssets.mjs.\nexport const SINGLE_SEED_ART = '+JSON.stringify(data,null,2)+';\n');
console.log('Registered '+items.length+' single-seed native PNGs.');
